"""SQLite storage for scan history.

Scans are grouped by an anonymous device id generated by the browser. No
accounts are involved. Stats returned by get_stats() never include device ids.
"""

from __future__ import annotations

import json
import sqlite3
import threading
import uuid
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from typing import Any, Iterator

from app.config import settings

_write_lock = threading.Lock()

SCHEMA = """
CREATE TABLE IF NOT EXISTS scans (
    id              TEXT PRIMARY KEY,
    device_id       TEXT NOT NULL,
    created_at      TEXT NOT NULL,
    predicted_class TEXT NOT NULL,
    confidence      REAL NOT NULL,
    probabilities   TEXT NOT NULL,
    thumbnail       BLOB
);
CREATE INDEX IF NOT EXISTS idx_scans_device ON scans (device_id, created_at);
CREATE INDEX IF NOT EXISTS idx_scans_created ON scans (created_at);
"""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@contextmanager
def _connect() -> Iterator[sqlite3.Connection]:
    settings.database_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(settings.database_path, check_same_thread=False, timeout=10)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db() -> None:
    with _write_lock, _connect() as conn:
        conn.executescript(SCHEMA)


def insert_scan(
    device_id: str,
    predicted_class: str,
    confidence: float,
    probabilities: dict[str, float],
    thumbnail: bytes | None,
) -> str:
    scan_id = uuid.uuid4().hex
    with _write_lock, _connect() as conn:
        conn.execute(
            """INSERT INTO scans (id, device_id, created_at, predicted_class, confidence, probabilities, thumbnail)
               VALUES (?, ?, ?, ?, ?, ?, ?)""",
            (scan_id, device_id, _now(), predicted_class, confidence, json.dumps(probabilities), thumbnail),
        )
    return scan_id


def list_scans(device_id: str, limit: int, offset: int) -> tuple[list[dict[str, Any]], int]:
    with _connect() as conn:
        total = conn.execute("SELECT COUNT(*) FROM scans WHERE device_id = ?", (device_id,)).fetchone()[0]
        rows = conn.execute(
            """SELECT id, created_at, predicted_class, confidence, (thumbnail IS NOT NULL) AS has_thumbnail
               FROM scans WHERE device_id = ? ORDER BY created_at DESC LIMIT ? OFFSET ?""",
            (device_id, limit, offset),
        ).fetchall()
    return [dict(row) for row in rows], total


def get_scan(device_id: str, scan_id: str) -> dict[str, Any] | None:
    with _connect() as conn:
        row = conn.execute(
            "SELECT id, created_at, predicted_class, confidence, probabilities, (thumbnail IS NOT NULL) AS has_thumbnail "
            "FROM scans WHERE id = ? AND device_id = ?",
            (scan_id, device_id),
        ).fetchone()
    if row is None:
        return None
    data = dict(row)
    data["probabilities"] = json.loads(data["probabilities"])
    return data


def get_thumbnail(device_id: str, scan_id: str) -> bytes | None:
    with _connect() as conn:
        row = conn.execute(
            "SELECT thumbnail FROM scans WHERE id = ? AND device_id = ?", (scan_id, device_id)
        ).fetchone()
    return row["thumbnail"] if row and row["thumbnail"] is not None else None


def delete_scan(device_id: str, scan_id: str) -> bool:
    with _write_lock, _connect() as conn:
        cursor = conn.execute("DELETE FROM scans WHERE id = ? AND device_id = ?", (scan_id, device_id))
        return cursor.rowcount > 0


def get_stats(days: int = 14, recent_limit: int = 8) -> dict[str, Any]:
    today = datetime.now(timezone.utc).date()
    window_start = (today - timedelta(days=days - 1)).isoformat()
    with _connect() as conn:
        total = conn.execute("SELECT COUNT(*) FROM scans").fetchone()[0]
        last_7 = conn.execute(
            "SELECT COUNT(*) FROM scans WHERE created_at >= ?",
            ((today - timedelta(days=6)).isoformat(),),
        ).fetchone()[0]
        by_class = conn.execute(
            "SELECT predicted_class, COUNT(*) AS n FROM scans GROUP BY predicted_class"
        ).fetchall()
        per_day = conn.execute(
            "SELECT substr(created_at, 1, 10) AS day, COUNT(*) AS n FROM scans "
            "WHERE substr(created_at, 1, 10) >= ? GROUP BY day",
            (window_start,),
        ).fetchall()
        recent = conn.execute(
            "SELECT created_at, predicted_class, confidence FROM scans ORDER BY created_at DESC LIMIT ?",
            (recent_limit,),
        ).fetchall()

    counts_by_day = {row["day"]: row["n"] for row in per_day}
    daily = [
        {"day": (today - timedelta(days=offset)).isoformat(),
         "count": counts_by_day.get((today - timedelta(days=offset)).isoformat(), 0)}
        for offset in range(days - 1, -1, -1)
    ]
    return {
        "total_scans": total,
        "scans_last_7_days": last_7,
        "by_class": {row["predicted_class"]: row["n"] for row in by_class},
        "daily": daily,
        "recent": [dict(row) for row in recent],
    }
